/* ------------------------------------------------------------------ *
 * 5. Numeric cross-check
 * ------------------------------------------------------------------ */

const CLAIM_KINDS = [
  { kind: "published", re: /(\d+)\s+published\b/gi },
  { kind: "approved", re: /(\d+)\s+approved\b/gi },
  { kind: "projected", re: /(\d+)\s+projected\b/gi },
];

function truthFor(kind, truth) {
  // published/projected both mean "rows that reach the public projection" =
  // approved rows minus delete-tier = the auditor's `publishable`.
  if (kind === "approved") return { value: truth.approved, basis: "rights-audit.approved (rows passing rights/published/price)" };
  return { value: truth.publishable, basis: "rights-audit.publishable (approved rows minus delete-tier)" };
}

function scanClaims(fileText, filePath) {
  const claims = [];
  fileText.split(/\r?\n/).forEach((line, idx) => {
    const flat = strip(line);
    for (const { kind, re } of CLAIM_KINDS) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(flat)) !== null) {
        claims.push({ file: filePath, line: idx + 1, kind, stated: Number(m[1]), context: flat.trim().slice(0, 160) });
      }
    }
  });
  return claims;
}

/**
 * Three scopes, because "stale" and "historical" are not the same thing:
 *   table   — the RELEASE_GATES Status column. This runner owns it and
 *             regenerates it, so a mismatch here is corrected in place.
 *   prose   — any other present-tense `.agent-state/*.md` line. A mismatch is
 *             a real SOURCE-OF-TRUTH-CONFLICT, but the runner only reports it:
 *             it cannot verify the surrounding sentence's arithmetic.
 *   ledger  — DECISIONS.md. An append-only record of dated decisions: its
 *             numbers are history by construction, so a mismatch there is a
 *             HISTORICAL-CLAIM, not a conflict, and editing it would destroy
 *             the audit trail. Reported for visibility, never acted on.
 */
function crossCheck(truth, parsed) {
  const conflicts = [];
  const agreements = [];
  const historical = [];

  const record = (claim, scope) => {
    const { value, basis } = truthFor(claim.kind, truth);
    const entry = { ...claim, computed: value, basis, scope };
    if (claim.stated === value) agreements.push(entry);
    else if (scope === "ledger") historical.push(entry);
    else conflicts.push(entry);
  };

  // (a) The table's Status column — this runner owns it and regenerates it.
  for (const row of parsed.rows) {
    for (const claim of scanClaims(row.status, rel(GATES_FILE))) {
      record({ ...claim, line: row.sourceLine, gate: row.id }, "table");
    }
  }

  // (b) Every other .agent-state/*.md line — reported, never rewritten.
  //     Two exclusions, both to keep the check from reading its own output:
  //     the table rows already handled above, and the generated note block,
  //     whose text quotes the very numbers it just corrected.
  const tableLineNumbers = new Set(parsed.rows.map((r) => r.sourceLine));
  for (const name of readdirSync(STATE_DIR).filter((f) => f.endsWith(".md")).sort()) {
    const file = path.join(STATE_DIR, name);
    const text = readFileSync(file, "utf8");
    const generated = new Set();
    if (file === GATES_FILE) {
      const lines = text.split(/\r?\n/);
      const from = lines.findIndex((l) => l.trim() === BEGIN_MARK);
      const to = lines.findIndex((l) => l.trim() === END_MARK);
      if (from >= 0 && to > from) for (let i = from; i <= to; i += 1) generated.add(i + 1);
    }
    for (const claim of scanClaims(text, rel(file))) {
      if (file === GATES_FILE && (tableLineNumbers.has(claim.line) || generated.has(claim.line))) continue;
      record(claim, name === "DECISIONS.md" ? "ledger" : "prose");
    }
  }

  return { conflicts, agreements, historical };
}

/* ------------------------------------------------------------------ *
 * 6. Execution
 * ------------------------------------------------------------------ */

/**
 * Fresh detail for the Status cell, taken from the child's own output. Bun
 * echoes the underlying command as `$ …` before running it; that echo is the
 * command, not a result, so it is dropped. Test-runner counters are preferred
 * over the last line because they are the number a reader actually wants.
 */
function tailOf(child) {
  const clean = (blob) => (blob ?? "").split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("$ "));
  const out = clean(child.stdout);
  const err = clean(child.stderr);
  const counters = [...out, ...err].filter((l) => /^(ℹ|#)\s*(tests|pass|fail|skipped|cancelled)\b/.test(l));
  if (counters.length > 0) return counters.join(", ").slice(0, 200);
  // A report printed as pretty JSON: keep its scalars, drop its paths. Absolute
  // local paths must not be baked into a tracked document.
  try {
    const parsed = JSON.parse(out.join("\n"));
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
      const scalars = Object.entries(parsed)
        .filter(([, v]) => typeof v === "number" || typeof v === "boolean")
        .map(([k, v]) => `${k}=${v}`);
      if (scalars.length > 0) return scalars.join(", ").slice(0, 200);
    }
  } catch {
    // not a JSON report; fall through to the last line
  }
  return (out[out.length - 1] ?? err[err.length - 1] ?? "").slice(0, 200);
}

function runGate(row, plan) {
  const details = [];
  let worstExit = 0;
  const started = Date.now();
  for (const step of plan.exec) {
    process.stdout.write(`  → ${step.display} … `);
    const t0 = Date.now();
    const child = spawnSync(step.binary, step.args, { cwd: ROOT, encoding: "utf8", shell: false });
    const ms = Date.now() - t0;
    if (child.error) {
      console.log(`spawn-error ${child.error.code ?? child.error.message} (${(ms / 1000).toFixed(1)}s)`);
      log({ gate: row.id, event: "step", command: step.display, mappedFrom: step.mappedFrom, exitCode: null, spawnError: child.error.code ?? child.error.message, durationMs: ms });
      worstExit = worstExit || 127;
      details.push(`${step.display}: spawn-error ${child.error.code ?? child.error.message}`);
      continue;
    }
    console.log(`exit ${child.status} (${(ms / 1000).toFixed(1)}s)`);
    log({ gate: row.id, event: "step", command: step.display, mappedFrom: step.mappedFrom, exitCode: child.status, durationMs: ms });
    if (child.status !== 0) {
      worstExit = worstExit || child.status;
      if (child.stderr) console.error(child.stderr.split(/\r?\n/).slice(-25).join("\n"));
    }
    const tail = tailOf(child);
    if (tail) details.push(tail);
  }
  return { exitCode: worstExit, durationMs: Date.now() - started, detail: details.join("; ") };
}

