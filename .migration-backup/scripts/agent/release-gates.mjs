/**
 * Release-gate runner — executes `.agent-state/RELEASE_GATES.md` instead of
 * trusting it, and refuses to certify a stale source of truth.
 *
 * Three things this replaces, and why:
 *
 *  1. The Command column is a DOCUMENT, not an authority. It reads `npm test`,
 *     `npm run build`, … while AGENTS.md declares bun canonical. This runner
 *     never shells out to npm/npx/pnpm/yarn: it maps each command to its bun
 *     equivalent, executes THAT, records the mapping, rewrites the column, and
 *     hard-aborts if a forbidden package manager ever reaches an argv[0].
 *
 *  2. The Status column was hand-maintained and drifted 48 artworks away from
 *     the catalog: it claimed "139 published" / "169 approved → 139 projected"
 *     against a catalog that computes 217 approved / 187 publishable. A
 *     freshness-by-date check cannot see that; a numeric cross-check can. Every
 *     `<N> published|approved|projected` claim in `.agent-state/*.md` is
 *     compared against `scripts/agent/rights-audit.mjs` (P10 — the single
 *     computation of catalog truth; this runner parses its JSON and never
 *     recomputes the numbers itself). A mismatch is SOURCE-OF-TRUTH-CONFLICT.
 *     Stated default resolution: the computed value wins.
 *
 *  3. PASS was assertable by typing it. Here PASS is derivable only from a
 *     captured child exit code that was written to the run log first. Anything
 *     that needs credentials, a live service, a browser, or an absent CLI is
 *     written NOT RUN with the reason. There is no third way to reach PASS.
 *
 * SCOPE OF AUTOMATIC REWRITE (deliberately narrow, stated honestly):
 *   - The Status column of the RELEASE_GATES table is machine-generated from
 *     this run. Prior hand-written detail is NOT preserved — that detail is
 *     precisely what went stale. Fresh detail is the tail of the child's own
 *     output plus, for catalog gates, the computed counts.
 *   - Numeric claims OUTSIDE that table (other `.agent-state/*.md` files, the
 *     launch-blocker prose) are REPORTED, never silently rewritten.
 *     `DECISIONS.md` in particular is an append-only ledger whose superseded
 *     numbers are correct *as history*; rewriting them would destroy the audit
 *     trail the ADR exists to provide.
 *
 * Modes:
 *   (default)   execute every mapped gate, rewrite the table, append an ADR
 *               when a conflict was corrected
 *   --dry-run   run the cross-check and print the command plan; execute
 *               nothing, write nothing
 *   --today=YYYY-MM-DD   override the Status date (default: system date)
 *
 * FAIL-MODE: closed. An unresolvable bun, an unparseable table, an unreadable
 * catalog, or a forbidden spawn aborts without writing a status. Exit codes:
 *   0 every executed gate passed
 *   1 an executed gate failed
 *   2 the runner could not establish ground truth (nothing was certified)
 *
 * Run log: C:\Users\serge\.claude\logs\release-gates.jsonl (append-only JSONL,
 * on C:, outside both repos, so it is never part of any working tree).
 */
import { spawnSync } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const STATE_DIR = path.join(ROOT, ".agent-state");
const GATES_FILE = path.join(STATE_DIR, "RELEASE_GATES.md");
const DECISIONS_FILE = path.join(STATE_DIR, "DECISIONS.md");
const AUDITOR = path.join(ROOT, "scripts", "agent", "rights-audit.mjs");
const LOG_DIR = path.join(homedir(), ".claude", "logs");
const LOG = path.join(LOG_DIR, "release-gates.jsonl");

const DRY_RUN = process.argv.includes("--dry-run");
const TODAY = (process.argv.find((a) => a.startsWith("--today="))?.slice("--today=".length)) ||
  new Date().toISOString().slice(0, 10);
const RUN_ID = `${TODAY}T${new Date().toISOString().slice(11, 19)}Z`;

const BEGIN_MARK = "<!-- release-gates:begin (generated by scripts/agent/release-gates.mjs — do not hand-edit) -->";
const END_MARK = "<!-- release-gates:end -->";

/** Package managers this runner must never spawn. AGENTS.md: bun is canonical. */
const FORBIDDEN_RUNNERS = /^(npm|npx|pnpm|yarn)(\.cmd|\.exe)?$/i;

function abort(reason) {
  console.error(`\n[release-gates] ABORT: ${reason}`);
  console.error("[release-gates] Nothing was certified and no file was rewritten.");
  process.exit(2);
}

function log(row) {
  const full = { v: 1, ts: new Date().toISOString(), actor: "release-gates", run: RUN_ID, ...row };
  if (DRY_RUN) return full;
  try {
    mkdirSync(LOG_DIR, { recursive: true });
    appendFileSync(LOG, JSON.stringify(full) + "\n");
  } catch (cause) {
    // A logging failure must not manufacture a PASS: PASS is derived from the
    // in-memory record only after this call returns, and certifyStatus below
    // refuses any row that is not marked logged.
    full.logged = false;
    full.logError = cause.code ?? cause.message;
    return full;
  }
  full.logged = true;
  return full;
}

/* ------------------------------------------------------------------ *
 * 1. Ground truth: P10's auditor. Parsed, never reimplemented.
 * ------------------------------------------------------------------ */

function computeCatalogTruth() {
  if (!existsSync(AUDITOR)) abort(`rights auditor absent at ${AUDITOR} — cannot establish catalog truth.`);
  const child = spawnSync(process.execPath, [AUDITOR], { cwd: ROOT, encoding: "utf8", shell: false });
  if (child.error) abort(`rights-audit spawn failed: ${child.error.code ?? child.error.message}`);
  if (child.status !== 0) abort(`rights-audit exited ${child.status} — refusing to cross-check against an untrusted count.\n${child.stderr ?? ""}`);
  let report;
  try {
    report = JSON.parse(child.stdout);
  } catch (cause) {
    abort(`rights-audit output is not JSON (${cause.message}) — refusing to guess catalog counts.`);
  }
  for (const key of ["total", "approved", "publishable"]) {
    if (typeof report[key] !== "number") abort(`rights-audit report is missing numeric "${key}" — schema drift; refusing to cross-check.`);
  }
  return report;
}

/* ------------------------------------------------------------------ *
 * 2. Table parsing
 * ------------------------------------------------------------------ */

function splitCells(line) {
  return line.replace(/^\s*\|/, "").replace(/\|\s*$/, "").split("|").map((c) => c.trim());
}

function parseGatesDoc(text) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => /^\s*\|\s*Gate\s*\|/i.test(l));
  if (start < 0) abort(`${GATES_FILE} has no "| Gate |" table header — its structure changed; refusing to guess.`);
  if (!/^\s*\|[\s:|-]+\|\s*$/.test(lines[start + 1] ?? "")) abort(`${GATES_FILE} table header is not followed by a separator row — refusing to guess.`);
  let end = start + 2;
  while (end < lines.length && /^\s*\|/.test(lines[end])) end += 1;

  const rows = [];
  for (let i = start + 2; i < end; i += 1) {
    const cells = splitCells(lines[i]);
    if (cells.length < 4) abort(`${GATES_FILE} line ${i + 1} has ${cells.length} cells, expected 4 — refusing to guess.`);
    const [gate, requirement, command, status] = cells;
    const id = /\*\*(G\d+)\s*:/.exec(gate)?.[1] ?? /^(G\d+)\b/.exec(strip(gate))?.[1] ?? null;
    if (!id) abort(`${GATES_FILE} line ${i + 1} has no recognisable gate id in "${gate}" — refusing to guess.`);
    rows.push({ id, gate, requirement, command, status, sourceLine: i + 1 });
  }
  if (rows.length === 0) abort(`${GATES_FILE} table has no data rows.`);
  return { lines, headerIndex: start, tableEnd: end, rows };
}

function strip(s) {
  return s.replace(/[*`]/g, "");
}

/** Repo-relative, forward-slashed — the same path shape the docs already use. */
function rel(file) {
  return path.relative(ROOT, file).split(path.sep).join("/");
}

function cellSafe(s) {
  return String(s)
    .split(homedir())
    .join("~")
    .split(ROOT)
    .join(".")
    .replace(/\r?\n/g, " ")
    .replace(/\|/g, "\\|")
    .replace(/\s+/g, " ")
    .trim();
}

/* ------------------------------------------------------------------ *
 * 3. Command mapping — npm is never spawned
 * ------------------------------------------------------------------ */

function resolveBun() {
  const cherry = "C:\\Users\\serge\\.cherrystudio\\bin\\bun.exe";
  if (existsSync(cherry)) return cherry;
  const probe = spawnSync("bun", ["--version"], { shell: false, encoding: "utf8" });
  if (probe.status === 0) return "bun";
  return null;
}

/**
 * Map one backticked token from the Command column.
 * Returns an executable plan, or a non-executable reference with the reason
 * it is not runnable. A token is executable only if it names a known package
 * runner or an existing test file; anything else is a documentation reference.
 */
function mapCommand(raw, bun) {
  const text = raw.trim();
  const tokens = text.split(/\s+/);
  const head = tokens[0];

  if (head === "npm" || head === "pnpm" || head === "yarn") {
    const rest = tokens[1] === "run" ? tokens.slice(2) : tokens.slice(1);
    if (rest.length === 0) return { kind: "reference", text, why: `"${text}" names no script` };
    return {
      kind: "exec",
      binary: bun,
      args: ["run", ...rest],
      display: `bun run ${rest.join(" ")}`,
      mappedFrom: text,
      mapping: `${text} → bun run ${rest.join(" ")}`,
    };
  }

  // Already-canonical forms — including the ones a previous run wrote back into
  // the column. Re-parsing this file must be idempotent, or the runner demotes
  // its own output to NOT RUN on the next run.
  if (head === "bun") {
    return { kind: "exec", binary: bun, args: tokens.slice(1), display: text, mappedFrom: null, mapping: null };
  }
  if (head === "node") {
    return { kind: "exec", binary: process.execPath, args: tokens.slice(1), display: text, mappedFrom: null, mapping: null };
  }

  if (/^tests\/.+\.test\.tsx?$/.test(text) && existsSync(path.join(ROOT, text))) {
    const args = ["--test", "--experimental-strip-types", text];
    return {
      kind: "exec",
      binary: process.execPath,
      args,
      display: `node ${args.join(" ")}`,
      mappedFrom: text,
      mapping: `${text} (a test file, not a command) → node --test --experimental-strip-types ${text}`,
    };
  }

  return { kind: "reference", text, why: `"${text}" is a file/artifact reference, not a runnable command` };
}

function extractTokens(commandCell) {
  const found = [...commandCell.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
  return found;
}

/* ------------------------------------------------------------------ *
 * 4. Preconditions — the only route to NOT RUN
 * ------------------------------------------------------------------ */

function probeCli(bin) {
  const child = spawnSync(bin, ["--version"], { shell: false, encoding: "utf8" });
  if (child.error) return { present: false, why: `spawn ${child.error.code ?? child.error.message}` };
  if (child.status !== 0) return { present: false, why: `exit ${child.status}` };
  return { present: true, version: (child.stdout ?? "").trim().split(/\r?\n/)[0] };
}

