/**
 * PASS is derivable ONLY from a logged, numeric, zero exit code. There is no
 * other branch that can produce the string "PASS".
 */
function certifyStatus(row) {
  const rec = results.get(row.id);
  if (!rec) return { text: "**NOT RUN** — the runner produced no record for this gate", pass: false };
  if (rec.status === "not-run") return { text: `**NOT RUN** — ${cellSafe(rec.reason)}`, pass: false };
  if (rec.logged !== true) {
    return { text: `**NOT RUN** — the gate executed (exit ${rec.exitCode}) but its result could not be written to the run log (${cellSafe(rec.logError ?? "unknown")}); an uncaptured result is not a certification`, pass: false };
  }
  if (typeof rec.exitCode !== "number") return { text: "**NOT RUN** — no exit code was captured", pass: false };
  const secs = `${(rec.durationMs / 1000).toFixed(1)}s`;
  const counts = ["G4", "G6"].includes(row.id)
    ? ` — computed catalog truth: ${truth.approved} approved → ${truth.publishable} publishable (${truth.total - truth.publishable} delete-tier excluded), per \`node scripts/agent/rights-audit.mjs\``
    : "";
  const detail = rec.detail ? ` — ${cellSafe(rec.detail)}` : "";
  if (rec.exitCode === 0) return { text: `**PASS** (exit 0, ${secs}, ${RUN_ID})${detail}${counts}`, pass: true };
  return { text: `**FAIL** (exit ${rec.exitCode}, ${secs}, ${RUN_ID})${detail}${counts}`, pass: false };
}

// ---- rewrite the document --------------------------------------------
const newHeader = `| Gate | Requirement | Command / Check (bun — mapped from the documented command) | Status (${TODAY}) |`;
const newRows = parsed.rows.map((row) => {
  const plan = plans.get(row.id);
  const commandCell = [
    ...plan.exec.map((s) => `\`${s.display}\``),
    ...plan.refs.map((r) => `\`${r.text}\``),
  ].join(", ") || cellSafe(strip(row.command));
  return `| ${row.gate} | ${row.requirement} | ${commandCell} | ${certifyStatus(row).text} |`;
});

const mappings = [...new Set([...plans.values()].flatMap((p) => p.exec.map((s) => s.mapping).filter(Boolean)))];
const notRun = parsed.rows.filter((r) => results.get(r.id)?.status === "not-run");

const noteBlock = [
  BEGIN_MARK,
  "",
  `**How this table was produced.** \`node scripts/agent/release-gates.mjs\` executed it on ${TODAY} (run \`${RUN_ID}\`). Every Status cell above is derived from a child-process exit code captured during that run and written to \`~/.claude/logs/release-gates.jsonl\`; no cell can read **PASS** without one.`,
  "",
  `**Command mapping (npm is never spawned — \`bun\` is canonical per AGENTS.md).** The documented Command column was rewritten to the form actually executed:`,
  "",
  ...(mappings.length > 0 ? mappings.map((m) => `- \`${m}\``) : ["- (no mapping needed — every documented command was already canonical)"]),
  "",
  `**NOT RUN (${notRun.length}).** A gate that needs credentials, a live service, a browser, or an absent CLI is recorded NOT RUN with its reason. It never becomes PASS by default:`,
  "",
  ...(notRun.length > 0
    ? notRun.map((r) => `- **${r.id}** — ${cellSafe(results.get(r.id).reason)}`)
    : ["- (none)"]),
  "",
  `**Numeric cross-check against computed catalog truth.** \`node scripts/agent/rights-audit.mjs\` reports **${truth.total} total / ${truth.approved} approved / ${truth.publishable} publishable** (${truth.total - truth.publishable} delete-tier excluded). Every \`<N> published|approved|projected\` claim in \`.agent-state/*.md\` was compared against it: **${agreements.length} agree, ${conflicts.length} conflict, ${historical.length} superseded ledger claim(s)** in \`DECISIONS.md\` (an append-only record of dated decisions — its numbers are history by construction and are never rewritten).`,
  ...(conflicts.length > 0
    ? [
        "",
        ...conflicts.map(
          (c) =>
            `- \`SOURCE-OF-TRUTH-CONFLICT\` — \`${c.file}\`:${c.line}${c.gate ? ` (${c.gate})` : ""} stated **${c.stated} ${c.kind}**; \`catalog/approved-artworks.json\` computes **${c.computed}** (${c.basis}). Computed value wins${c.scope === "table" ? "; the Status column above carries the corrected number." : "; reported only — this runner rewrites no prose or append-only ledger line."}`,
        ),
      ]
    : []),
  "",
  END_MARK,
].join("\n");

const before = parsed.lines.slice(0, parsed.headerIndex);
let after = parsed.lines.slice(parsed.tableEnd);
const oldBegin = after.findIndex((l) => l.trim() === BEGIN_MARK);
if (oldBegin >= 0) {
  const oldEnd = after.findIndex((l) => l.trim() === END_MARK);
  if (oldEnd < 0) abort(`${GATES_FILE} has an unterminated ${BEGIN_MARK} block.`);
  after = [...after.slice(0, oldBegin), ...after.slice(oldEnd + 1)];
}
while (after.length > 0 && after[0].trim() === "") after.shift();

const rewritten = [
  ...before,
  newHeader,
  parsed.lines[parsed.headerIndex + 1],
  ...newRows,
  "",
  noteBlock,
  "",
  ...after,
].join("\n");

writeFileSync(GATES_FILE, rewritten.endsWith("\n") ? rewritten : `${rewritten}\n`);
console.log(`\n[release-gates] rewrote ${rel(GATES_FILE)} (Status dated ${TODAY})`);

// ---- append an ADR when a conflict was corrected ----------------------
const corrected = conflicts.filter((c) => c.scope === "table");
if (corrected.length > 0) {
  const decisions = readFileSync(DECISIONS_FILE, "utf8");
  const nextAdr = String(
    Math.max(0, ...[...decisions.matchAll(/^##\s+ADR-(\d+)/gm)].map((m) => Number(m[1]))) + 1,
  ).padStart(3, "0");
  const reported = conflicts.filter((c) => c.scope !== "table");
  const adr = [
    "",
    `## ADR-${nextAdr} (${TODAY}): Release-Gate Status Table Corrected Against Computed Catalog Truth`,
    "",
    `- **Context**: \`.agent-state/RELEASE_GATES.md\` and \`catalog/approved-artworks.json\` are both designated sources of truth, and they disagreed. The hand-maintained Status column asserted ${corrected.map((c) => `**${c.stated} ${c.kind}** (${c.gate})`).join(", ")}, while the catalog computes **${truth.total} total / ${truth.approved} approved / ${truth.publishable} publishable** (${truth.total - truth.publishable} delete-tier excluded). A freshness-by-date check cannot detect this class of drift; a numeric cross-check can.`,
    `- **Decision**: The computed value wins. \`scripts/agent/release-gates.mjs\` rewrote the Status column from this run's captured exit codes and the computed counts. Corrections (old → new): ${corrected.map((c) => `${c.gate ?? c.file}: ${c.stated} ${c.kind} → ${c.computed} ${c.kind}`).join("; ")}.`,
    `- **Evidence command**: \`node scripts/agent/rights-audit.mjs\` (P10's auditor; this runner parses its JSON and does not recompute the counts) → \`{"total":${truth.total},"approved":${truth.approved},"publishable":${truth.publishable}}\`, captured ${TODAY} in run \`${RUN_ID}\` and logged to \`~/.claude/logs/release-gates.jsonl\`.`,
    `- **Scope**: only the RELEASE_GATES Status column is machine-rewritten. ${reported.length > 0 ? `${reported.length} further numeric claim(s) outside it were reported, not rewritten (${reported.map((c) => `\`${c.file}\`:${c.line} states ${c.stated} ${c.kind}, computed ${c.computed}`).join("; ")}) — the runner cannot verify the surrounding sentence's arithmetic, so a human decides whether those are stale status or correct history.` : "No present-tense numeric claim outside it conflicted with computed truth this run."} \`DECISIONS.md\` is append-only: ${historical.length} superseded number(s) in earlier ADRs are correct *as history*, are reported as \`HISTORICAL-CLAIM\` rather than as conflicts, and are never edited.`,
    `- **Impact**: The release-gate table is now machine-generated per run. Any gate needing credentials, a live service, a browser, or an absent CLI reads **NOT RUN** with its reason, and **PASS** is derivable only from a logged exit code. Re-running the runner after this correction finds no table conflict and appends no further ADR.`,
    "",
  ].join("\n");
  appendFileSync(DECISIONS_FILE, decisions.endsWith("\n") ? adr : `\n${adr}`);
  console.log(`[release-gates] appended ADR-${nextAdr} to ${rel(DECISIONS_FILE)} (append-only; no existing entry edited)`);
  log({ event: "adr", id: `ADR-${nextAdr}`, file: rel(DECISIONS_FILE), corrections: corrected.map((c) => ({ gate: c.gate, kind: c.kind, old: c.stated, new: c.computed })) });
}

// ---- summary ----------------------------------------------------------
const tally = { pass: 0, fail: 0, "not-run": 0 };
for (const row of parsed.rows) tally[results.get(row.id).status] += 1;
console.log(`\n[release-gates] ${tally.pass} PASS · ${tally.fail} FAIL · ${tally["not-run"]} NOT RUN · ${conflicts.length} conflict(s)`);
